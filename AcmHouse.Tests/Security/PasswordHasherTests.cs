using AcmHouse.Security;
using Xunit;

namespace AcmHouse.Tests.Security
{
    public class PasswordHasherTests
    {
        [Fact]
        public void Verify_ReturnsTrue_ForThePasswordThatWasHashed()
        {
            string hash = PasswordHasher.Hash("Demo1234");

            Assert.True(PasswordHasher.Verify("Demo1234", hash));
        }

        [Fact]
        public void Verify_ReturnsFalse_ForAnotherPassword()
        {
            string hash = PasswordHasher.Hash("Demo1234");

            Assert.False(PasswordHasher.Verify("demo1234", hash));
        }

        [Fact]
        public void Hash_UsesRandomSalt_SoTheSamePasswordGivesDifferentHashes()
        {
            Assert.NotEqual(PasswordHasher.Hash("Demo1234"), PasswordHasher.Hash("Demo1234"));
        }

        [Fact]
        public void Hash_DoesNotContainThePassword()
        {
            Assert.DoesNotContain("Demo1234", PasswordHasher.Hash("Demo1234"));
        }

        [Fact]
        public void Verify_AcceptsHashStoredInTheDemoDatabase()
        {
            // Generated by Database/seed-demo-data.sql for the demo employees.
            const string storedHash = "PBKDF2$100000$4g4wzrh642a/hOhUktOw0Q==$KYNXFNQXq/pPuFFlLQkGYTRokjlPPb13fO0GppEVfDo=";

            Assert.True(PasswordHasher.Verify("Demo1234", storedHash));
            Assert.False(PasswordHasher.Verify("Admin1234", storedHash));
        }

        [Theory]
        [InlineData(null)]
        [InlineData("")]
        [InlineData("1234")]
        [InlineData("PBKDF2$abc$c2FsdA==$aGFzaA==")]
        [InlineData("PBKDF2$100000$not-base64$aGFzaA==")]
        [InlineData("MD5$100000$c2FsdA==$aGFzaA==")]
        public void Verify_ReturnsFalse_ForMalformedHash(string storedHash)
        {
            Assert.False(PasswordHasher.Verify("1234", storedHash));
        }
    }
}
